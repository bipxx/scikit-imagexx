bool data_checkerboard_u8_into(std::uint8_t* output, std::size_t count) noexcept {
    if (!output || count < data_checkerboard_elements) {
        return false;
    }
    std::uint8_t* cursor = output;
    for (const std::uint8_t code : kRuns) {
        const std::size_t run = static_cast<std::size_t>(code >> 3) + 1;
        const std::uint8_t value = kPalette[code & 7];
        cursor = std::fill_n(cursor, run, value);
    }
    return true;
}

