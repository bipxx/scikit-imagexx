// Horizontal edges use the two rolling z planes. Vertical edges and centers
// are valid for one slab only. Vertices retain first-encounter order.
class Slab {
public:
    Slab(std::size_t width, std::size_t height, std::size_t step, MarchingCubesMesh& mesh)
        : step_(step), mesh_(mesh),
          edge_offsets_{0, 4, 3 * width, 1, 0, 4, 3 * width, 1,
                        2, 5, 3 * width + 5, 3 * width + 2},
          low_(width * height * 3, -1), high_(width * height * 3, -1) {}

    void advance() {
        low_.swap(high_);
        std::fill(high_.begin(), high_.end(), -1);
    }

    void append(const double* v, Triangulation tiling, std::size_t x, std::size_t y,
                std::size_t z, std::size_t slab_base) {
        const auto limits = std::minmax_element(v, v + 8);
        const auto range = static_cast<float>(*limits.second - *limits.first);
        double weights[8];
        double gradients[8][3];
        for (int i = 0; i < 8; ++i) {
            weights[i] = 1 / (epsilon + std::abs(v[i]));
            // Corner numbering goes clockwise, but the reference looks
            // up gradients for edge endpoints in binary-coordinate order.
            const int xlow = i & 2 ? i | 1 : i & ~1;
            const int ylow = (i & 2) ? (i ^ 3) : i;
            const int zlow = i & 3;
            gradients[i][0] = v[xlow] - v[xlow ^ 1];
            gradients[i][1] = v[ylow] - v[ylow ^ 3];
            gradients[i][2] = v[zlow] - v[zlow | 4];
        }
        std::array<float, 3> center_gradient{};
        std::int32_t center_index = -1;
        const std::array<std::size_t, 3> origin{x, y, z};
        auto* low = low_.data() + slab_base;
        auto* high = high_.data() + slab_base;
        for (int triangle = 0; triangle < tiling.triangles; ++triangle) {
            std::array<std::int32_t, 3> face{};
            for (int corner = 0; corner < 3; ++corner) {
                const int edge = tiling.edges[triangle * 3 + corner];
                auto& index = edge == 12 ? center_index
                    : (edge >= 4 && edge < 8 ? high : low)[edge_offsets_[edge]];
                if (edge == 12) {
                    if (index < 0) {
                        std::array<double, 3> sums{}, gradient{};
                        double total = 0;
                        for (int i = 0; i < 8; ++i) {
                            total += weights[i];
                            for (int d = 0; d < 3; ++d) {
                                sums[d] += corners[i][d] * weights[i];
                                gradient[d] += gradients[i][d] * weights[i];
                            }
                        }
                        index = add_vertex(origin, sums, total);
                        for (int d = 0; d < 3; ++d) {
                            center_gradient[d] = static_cast<float>(gradient[d]);
                        }
                    }
                    for (int d = 0; d < 3; ++d) {
                        mesh_.normals[index][d] += center_gradient[d];
                    }
                } else {
                    const int a = edges[edge][0], b = edges[edge][1];
                    if (index < 0) {
                        std::array<double, 3> sums{};
                        for (int d = 0; d < 3; ++d) {
                            sums[d] = corners[a][d] * weights[a] + corners[b][d] * weights[b];
                        }
                        index = add_vertex(origin, sums, weights[a] + weights[b]);
                    }
                    const auto aw = static_cast<float>(weights[a]);
                    const auto bw = static_cast<float>(weights[b]);
                    const int ai = a ^ ((a & 2) >> 1), bi = b ^ ((b & 2) >> 1);
                    for (int d = 0; d < 3; ++d) {
                        mesh_.normals[index][d] += static_cast<float>(gradients[ai][d] * aw);
                        mesh_.normals[index][d] += static_cast<float>(gradients[bi][d] * bw);
                    }
                }
                face[corner] = index;
                mesh_.values[index] = std::max(mesh_.values[index], range);
            }
            mesh_.faces.push_back(face);
        }
    }

private:
    std::int32_t add_vertex(const std::array<std::size_t, 3>& origin,
                            const std::array<double, 3>& sums, double total) {
        if (mesh_.vertices.size() >= static_cast<std::size_t>(INT32_MAX)) {
            throw std::overflow_error("marching cubes vertex index exceeds int32");
        }
        std::array<float, 3> point{};
        for (int d = 0; d < 3; ++d) {
            point[d] = static_cast<float>(static_cast<double>(origin[d])
                + static_cast<double>(step_) * sums[d] / total);
        }
        const auto index = static_cast<std::int32_t>(mesh_.vertices.size());
        mesh_.vertices.push_back(point);
        mesh_.normals.emplace_back();
        mesh_.values.push_back(0);
        return index;
    }

    std::size_t step_;
    MarchingCubesMesh& mesh_;
    const std::array<std::size_t, 12> edge_offsets_;
    std::vector<std::int32_t> low_, high_;
};

