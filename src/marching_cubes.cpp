template<std::size_t N>
Triangulation tiling(const std::int8_t (&row)[N]) {
    static_assert(N % 3 == 0);
    return {row, static_cast<int>(N / 3)};
}

bool test_face(const double* v, int face) {
    const auto& f = face_corners[std::abs(face) - 1];
    const double determinant = v[f[0]] * v[f[2]] - v[f[1]] * v[f[3]];
    return std::abs(determinant) < epsilon ? face >= 0 : face * v[f[0]] * determinant >= 0;
}

bool test_interior(const double* v, int edge, int sign) {
    double a = 0, b, c, d;
    if (edge < 0) {
        const double da = v[4] - v[0], db = v[7] - v[3];
        const double dc = v[6] - v[2], dd = v[5] - v[1];
        const double quadratic = da * dc - db * dd;
        const double linear = v[2] * da + v[0] * dc - v[1] * db - v[3] * dd;
        const double t = -linear / (2 * quadratic + epsilon);
        if (t < 0 || t > 1) {
            return sign > 0;
        }
        a = v[0] + da * t;
        b = v[3] + db * t;
        c = v[2] + dc * t;
        d = v[1] + dd * t;
    } else {
        const auto& e = section_edges[edge];
        const double t = v[e[0]] / (v[e[0]] - v[e[1]] + epsilon);
        b = v[e[2]] + (v[e[3]] - v[e[2]]) * t;
        c = v[e[4]] + (v[e[5]] - v[e[4]]) * t;
        d = v[e[6]] + (v[e[7]] - v[e[6]]) * t;
    }
    const int bits = (a >= 0) + 2 * (b >= 0) + 4 * (c >= 0) + 8 * (d >= 0);
    switch (bits) {
    case 5: return a * c - b * d < epsilon && sign > 0;
    case 10: return a * c - b * d >= epsilon && sign > 0;
    case 7: case 11: case 13: case 14: case 15: return sign < 0;
    default: return sign > 0;
    }
}

