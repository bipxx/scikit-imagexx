namespace {
std::size_t checks = 0;
std::map<std::pair<std::uint64_t,std::uint64_t>,std::size_t> nan_encoding_differences;
void require(bool okay, const char* message) {
    if (!okay) throw std::runtime_error(message);
    ++checks;
}
template<class F> void rejects(F function) {
    try { function(); } catch (const std::exception&) { ++checks; return; }
    throw std::runtime_error("invalid descriptor accepted");
}
template<class T> std::uint64_t bits(T value) {
    std::uint64_t raw=0; std::memcpy(&raw,&value,sizeof(T)); return raw;
}
template<class T> void controls(skimagexx::TvReductionType type) {
    using namespace skimagexx;
    for (auto profile : {TvReductionProfile::numpy_1244_buffered,
                         TvReductionProfile::numpy_254_aligned_contiguous}) {
        TvReductionPlan plan{profile,16};
        require(tv_sum_contiguous({nullptr,0,type},plan).bits==bits(T(0)),"empty identity");
        std::vector<T> a(129,-T(0)), out(129,T(99));
        require(tv_sum_contiguous({a.data(),a.size(),type},plan).bits==bits(T(0)),"outer zero identity");
        require(tv_square_contiguous_into({a.data(),a.size(),type},out.data())==0,"zero square flags");
        for (T v:out) require(bits(v)==bits(T(0)),"negative zero square");
        for (std::size_t i=0;i<a.size();++i) a[i]=T(i%7);
        T exact=0; for (T v:a) exact=T(exact+v);
        require(tv_sum_contiguous({a.data(),a.size(),type},plan).bits==bits(exact),"exact integer sum");
        tv_square_contiguous_into({a.data(),a.size(),type},out.data());
        for (std::size_t i=0;i<a.size();++i) require(bits(out[i])==bits(T(a[i]*a[i])),"square values");
        rejects([&]{tv_square_contiguous_into({a.data(),a.size(),type},a.data());});
        rejects([&]{tv_square_contiguous_into({a.data(),a.size()-1,type},a.data()+1);});
        rejects([&]{tv_sum_contiguous({a.data(),a.size(),type},{profile,0});});
        rejects([&]{tv_sum_contiguous({reinterpret_cast<char*>(a.data())+1,1,type},plan);});
        rejects([&]{tv_sum_contiguous({nullptr,1,type},plan);});
        rejects([&]{tv_sum_contiguous({a.data(),std::numeric_limits<std::size_t>::max(),type},plan);});
        const auto saved=out;
        rejects([&]{tv_square_contiguous_into({nullptr,1,type},out.data());});
        require(std::memcmp(out.data(),saved.data(),out.size()*sizeof(T))==0,"prewrite guard");
        std::feclearexcept(FE_ALL_EXCEPT); std::feraiseexcept(FE_DIVBYZERO);
        const auto clean=tv_sum_contiguous({a.data(),a.size(),type},plan);
        require(clean.fp_status==0,"ambient flags leaked");
        require((std::fetestexcept(FE_DIVBYZERO)&FE_DIVBYZERO)!=0,"ambient flag lost");
        std::feclearexcept(FE_ALL_EXCEPT);
        T huge=std::numeric_limits<T>::max(), square=0;
        require((tv_square_contiguous_into({&huge,1,type},&square)&tv_fp_overflow)!=0,"square overflow flag");
        require(std::isinf(square),"overflow result");
        const int round=std::fegetround(); std::fesetround(FE_DOWNWARD);
        rejects([&]{tv_sum_contiguous({a.data(),a.size(),type},plan);});
        std::fesetround(round);
    }
}

// Oracle binary is generated by the ignored NumPy-only independent driver.
// Each record retains input and square bytes plus separate stage statuses.
std::uint64_t read64(std::istream& stream) {
    std::uint64_t value=0;
    stream.read(reinterpret_cast<char*>(&value),8);
    if(!stream) throw std::runtime_error("truncated oracle record");
    return value;
}
template<class T> void row(std::istream& stream,unsigned profile,std::uint64_t n,
                           std::uint64_t buffer,skimagexx::TvReductionType type) {
    using namespace skimagexx;
    const auto sum_bits=read64(stream), sum_flags=read64(stream);
    const auto square_flags=read64(stream), squared_sum_bits=read64(stream), squared_sum_flags=read64(stream);
    std::vector<T> input(n), expected(n), output(n);
    stream.read(reinterpret_cast<char*>(input.data()),std::streamsize(n*sizeof(T)));
    stream.read(reinterpret_cast<char*>(expected.data()),std::streamsize(n*sizeof(T)));
    if(!stream) throw std::runtime_error("truncated oracle arrays");
    const TvReductionPlan plan{profile==0?TvReductionProfile::numpy_1244_buffered:TvReductionProfile::numpy_254_aligned_contiguous,std::size_t(buffer)};
    const auto before=input;
    auto raw_equal=[](std::uint64_t a,std::uint64_t b){
        T x,y;std::memcpy(&x,&a,sizeof(T));std::memcpy(&y,&b,sizeof(T));
        if (std::isnan(x)&&std::isnan(y)) {
            // The frozen TV boundary excludes only result-NaN word encoding.
            // Keep every actual differing raw pair and its frequency in logs.
            if(a!=b) ++nan_encoding_differences[{a,b}];
            return true;
        }
        return a==b;
    };
    const auto sum=tv_sum_contiguous({input.data(),input.size(),type},plan);
    require(raw_equal(sum.bits,sum_bits),"NumPy sum raw scalar mismatch");
    require(sum.fp_status==sum_flags,"NumPy sum status mismatch");
    const auto flags=tv_square_contiguous_into({input.data(),input.size(),type},output.data());
    require(flags==square_flags,"NumPy square status mismatch");
    for(std::size_t i=0;i<output.size();++i)
        require(raw_equal(bits(output[i]),bits(expected[i])),"NumPy square raw word mismatch");
    const auto squared_sum=tv_sum_contiguous({output.data(),output.size(),type},plan);
    require(raw_equal(squared_sum.bits,squared_sum_bits),"NumPy squared sum raw scalar mismatch");
    require(squared_sum.fp_status==squared_sum_flags,"NumPy squared sum status mismatch");
    require(!n||std::memcmp(input.data(),before.data(),n*sizeof(T))==0,"oracle input mutated");
}
void oracle(const char* file) {
    std::ifstream stream(file,std::ios::binary);
    if(!stream) throw std::runtime_error("cannot open NumPy oracle");
    require(read64(stream)==0x31564445525654ull,"oracle magic");
    const auto records=read64(stream);
    for(std::uint64_t i=0;i<records;++i) {
        const auto type=read64(stream),profile=read64(stream),n=read64(stream),buffer=read64(stream);
        if(type==4) row<float>(stream,unsigned(profile),n,buffer,skimagexx::TvReductionType::float32);
        else if(type==8) row<double>(stream,unsigned(profile),n,buffer,skimagexx::TvReductionType::float64);
        else throw std::runtime_error("bad oracle type");
    }
    require(stream.peek()==std::char_traits<char>::eof(),"oracle trailing bytes");
}
}
int main(int argc,char** argv) {
    try {
        require(skimagexx::get_num_threads()==1,"global default worker count");
        for(int workers:{1,4}) {
#ifndef _OPENMP
            if(workers==4) {rejects([]{skimagexx::set_num_threads(4);});continue;}
#endif
            skimagexx::set_num_threads(workers);
            controls<float>(skimagexx::TvReductionType::float32);
            controls<double>(skimagexx::TvReductionType::float64);
            if(argc==2) oracle(argv[1]);
        }
        skimagexx::set_num_threads(1);
        for(const auto& difference:nan_encoding_differences)
            std::cout<<"result-NaN encoding actual="<<difference.first.first
                     <<" expected="<<difference.first.second<<" count="<<difference.second<<'\n';
        std::cout<<"TV reductions "<<checks<<" checks passed\n";
    } catch(const std::exception& error) {
        std::cerr<<"TV reductions FAILED after "<<checks<<": "<<error.what()<<'\n';return 1;
    }
}
