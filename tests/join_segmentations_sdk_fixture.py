"""Extract unchanged original intermediate bytes; stdlib only, no target calls."""
import base64
import hashlib
import json
from pathlib import Path
import zlib
ROOT=Path(__file__).resolve().parents[1]


def render():
    path=ROOT/'tests/fixtures/join_segmentations_originals_v1.json'
    assert hashlib.sha256(path.read_bytes()).hexdigest()=='0cb7da5d981bf95eb8895278bf9acc638ba3acd236625c48a00aa632a1b0a340'
    data=json.loads(path.read_bytes());rows=[]
    def raw(array):
        if 'raw' in array:return bytes.fromhex(array['raw'])
        value=zlib.decompress(base64.b64decode(array['raw_zlib_base64']))
        assert hashlib.sha256(value).hexdigest()==array['raw_sha256'];return value
    def vector(value):return '{'+','.join(str(v) for v in value)+'}'
    def descriptor(dtype):return '{'+str(int(dtype[2:]))+','+str(dtype[1]=='i').lower()+'}'
    for profile in ('minimum','modern'):
        for row in data['profiles'][profile]['rows']:
            f=row['source_frame']
            if not all(k in f for k in ('factor','s1_relabeled','s2_relabeled','j_initial')):continue
            a,b,out=(f[k] for k in ('s1_relabeled','s2_relabeled','j_initial'))
            if not (a['dtype']==b['dtype']==out['dtype'] and out['dtype'][1] in 'iu'):continue
            dtype=out['dtype'];width=int(dtype[2:]);factor=int.from_bytes(bytes.fromhex(f['factor']['raw']),'little',signed=f['factor']['dtype'][1]=='i')
            assert factor>0
            fields=[json.dumps(profile+':'+row['id']),'{'+str(width)+','+str(dtype[1]=='i').lower()+'}',str(factor),str(len(raw(a))//width),vector(raw(a)),vector(raw(b)),vector(raw(out))]
            # Full operation uses actual source inputs and returned bytes;
            # no join/relabel/math expected-output computation occurs here.
            original_a,original_b=row['input_before']['items'][0]['items']
            mapped=row['returned_map_aliases'] is not None
            accepted=row['error'] is None
            joined=row['result']['joined'] if mapped else row['result']
            if mapped:
                one,two=row['result']['maps'];keys=raw(one['keys']);first,second=raw(one['values']),raw(two['values'])
            else:keys=first=second=b''
            fields.extend([str(accepted).lower(),str(mapped).lower(),vector(original_a['shape']),vector(original_a['strides']),vector(original_b['strides']),vector(raw(original_a)),vector(raw(original_b)),vector(raw(joined)) if accepted else '{}',descriptor(joined['dtype']) if accepted else descriptor(dtype),vector(keys),vector(first),vector(second)])
            rows.append('{'+','.join(fields)+'}')
    return ('// Generated by tests/join_segmentations_sdk_fixture.py; verbatim saved bytes.\n'
        '#pragma once\n#include <skimagexx/join_segmentations.hpp>\n#include <cstdint>\n#include <vector>\n'
        'namespace join_segmentations_originals {\nstruct Row {const char* id;skimagexx::JoinType type;std::uint64_t factor;std::size_t count;std::vector<std::uint8_t> left,right,encoded;bool full,mapping;std::vector<std::size_t> shape;std::vector<std::ptrdiff_t> left_strides,right_strides;std::vector<std::uint8_t> original_left,original_right,joined;skimagexx::JoinType joined_type;std::vector<std::uint8_t> keys,first,second;};\n'
        'inline std::vector<Row> rows(){return {\n'+',\n'.join(rows)+'\n};}\n}\n')


if __name__=='__main__':
    (ROOT/'tests/fixtures/join_segmentations_originals_v1.hpp').write_text(render(),encoding='utf-8',newline='\n')
